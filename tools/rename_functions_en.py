# Avoid renaming SaveSystem.save / load conflicts — fix save aliases manually
RENAMES.pop("carregar", None)
RENAMES.pop("salvar", None)

# Sort longest first to avoid partial replacement issues
ORDERED = sorted(RENAMES.items(), key=lambda kv: len(kv[0]), reverse=True)


def replace_in_text(text: str) -> tuple[str, int]:
    count = 0
    for old, new in ORDERED:
        if old == new:
            continue
        pattern = re.compile(rf"(?<![A-Za-z0-9_]){re.escape(old)}(?=\s*\()")
        text, n = pattern.subn(new, text)
        count += n
    return text, count


def main() -> None:
    total_files = 0
    total_replacements = 0
    for dir_name in DIRS:
        base = ROOT / dir_name
        if not base.exists():
            continue
        for path in base.rglob("*.gd"):
            original = path.read_text(encoding="utf-8")
            updated, n = replace_in_text(original)
            if n:
                path.write_text(updated, encoding="utf-8")
                total_files += 1
                total_replacements += n
                print(f"{path.relative_to(ROOT)}: {n}")
    print(f"Done. {total_replacements} replacements in {total_files} files.")


if __name__ == "__main__":
    main()

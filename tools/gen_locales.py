def build_key_list() -> list[str]:
    keys: list[str] = []
    seen: set[str] = set()
    for key in locale_keys:
        if key not in seen:
            keys.append(key)
            seen.add(key)
    for item_id, _ in items:
        key = f"ITEM_{item_id}"
        if key not in seen:
            keys.append(key)
            seen.add(key)
    for key in SKILLS:
        if key not in seen:
            keys.append(key)
            seen.add(key)
    return keys


def po_escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def write_po(path: Path, translations: dict[str, str], *, empty: bool, language: str | None) -> int:
    keys = build_key_list()
    lines: list[str] = []
    if path.suffix == ".pot":
        lines.extend(
            [
                "# Translation template — Stickman Idle",
                "# Copy new msgid entries to locales/pt_BR.po and locales/en.po",
                "# Godot loads .po files listed in project.godot [internationalization]",
                "",
            ]
        )
    lines.append('msgid ""')
    lines.append('msgstr ""')
    if empty:
        lines.append('"Content-Type: text/plain; charset=UTF-8\\n"')
    else:
        lines.append('"Content-Type: text/plain; charset=UTF-8\\n"')
        lines.append(f'"Language: {language}\\n"')
    lines.append("")
    for key in keys:
        lines.append(f'msgid "{po_escape(key)}"')
        if empty:
            lines.append('msgstr ""')
        else:
            lines.append(f'msgstr "{po_escape(translations[key])}"')
        lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")
    return len(keys)


def main() -> None:
    missing_en = [key for key in locale_keys if key not in UI_EN]
    missing_pt = [key for key in locale_keys if key not in UI_PT]
    if missing_en or missing_pt:
        raise SystemExit(f"Missing translations EN={missing_en} PT={missing_pt}")

    en_trans = dict(UI_EN)
    pt_trans = dict(UI_PT)
    for item_id, pt_name in items:
        key = f"ITEM_{item_id}"
        en_trans[key] = ITEM_EN[item_id]
        pt_trans[key] = pt_name
    for key, (en_value, pt_value) in SKILLS.items():
        en_trans[key] = en_value
        pt_trans[key] = pt_value

    locales_dir = ROOT / "locales"
    en_count = write_po(locales_dir / "en.po", en_trans, empty=False, language="en")
    pt_count = write_po(locales_dir / "pt_BR.po", pt_trans, empty=False, language="pt_BR")
    pot_count = write_po(locales_dir / "messages.pot", {}, empty=True, language=None)

    print(f"locale_keys: {len(locale_keys)}")
    print(f"items: {len(items)}")
    print(f"skills: {len(SKILLS)}")
    print(f"en.po: {en_count} keys")
    print(f"pt_BR.po: {pt_count} keys")
    print(f"messages.pot: {pot_count} keys")


if __name__ == "__main__":
    main()
